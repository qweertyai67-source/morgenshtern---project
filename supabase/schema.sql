create table if not exists public.city_requests (
  id bigint generated by default as identity primary key,
  city text not null check (char_length(city) between 2 and 100),
  country text not null check (char_length(country) between 2 and 100),
  email text,
  consent boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.city_requests enable row level security;

-- Inserts are performed server-side with SUPABASE_SERVICE_ROLE_KEY.
